import { execFileSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { displayVersion } from './lib/version.mjs';

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
// An optional first argument replaces the output path (used by the unit test, so that it does not touch the real file).
const outputPath = process.argv[2] ?? join(repositoryRoot, 'src/config/version.generated.ts');

let raw = 'unknown';
try {
  raw = execFileSync('git', ['describe', '--tags', '--always', '--long', '--dirty'], {
    cwd: repositoryRoot,
    encoding: 'utf8',
  }).trim() || 'unknown';
} catch {
  // Builds from source archives or environments without Git still compile.
}

// PIP-018: users see `display` (vX.Y.Z, Z = tag patch + commits since the tag); `full` (the describe string) is for internal places such as the build log
// and the metadata of a saved file.
const display = displayVersion(raw);
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `// Generated by scripts/generate-version.mjs.\nexport const APP_VERSION_DISPLAY = ${JSON.stringify(display)};\nexport const APP_VERSION_FULL = ${JSON.stringify(raw)};\n// Alias of APP_VERSION_DISPLAY: the app.spec test of V1 compares the APP_VERSION token with this name.\nexport const APP_VERSION_RAW = APP_VERSION_DISPLAY;\n`,
);
console.log(`version ${display} (${raw})`);
