import { execFileSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(repositoryRoot, 'src/config/version.generated.ts');

let raw = 'unknown';
try {
  raw = execFileSync('git', ['describe', '--tags', '--always', '--long', '--dirty'], {
    cwd: repositoryRoot,
    encoding: 'utf8',
  }).trim() || 'unknown';
} catch {
  // Builds from source archives or environments without Git still compile.
}

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, `// Generated by scripts/generate-version.mjs.\nexport const APP_VERSION_RAW = ${JSON.stringify(raw)};\n`);
