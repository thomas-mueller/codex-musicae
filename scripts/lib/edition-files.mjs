// Edition files (V2-M3 S4, GEN-011, EDN-010): one place that turns an edition into the platform application ID. Pure logic;
// scripts/apply-edition.mjs writes the result, scripts/check-editions.mjs checks it.

const idOf = (tunables, key) => tunables.match(new RegExp(`\\b${key}:\\s*'([^']*)'`))?.[1];

/** The free and paid application IDs of src/config/tunables.ts (undefined when not found). */
export function appIds(tunables) {
  return { free: idOf(tunables, 'appId'), paid: idOf(tunables, 'appIdPaid') };
}

/** The edition named by a value; anything but 'paid' is the free app. */
export function editionOf(value) {
  return value === 'paid' ? 'paid' : 'free';
}

/** The generated files of an edition, by path relative to the repository root. */
export function editionFiles(tunables, edition) {
  const id = appIds(tunables)[editionOf(edition)];
  if (!id) throw new Error('appId / appIdPaid not found in tunables.ts');
  return {
    'android/edition.properties': `# Generated by scripts/apply-edition.mjs (${editionOf(edition)}); do not edit.\nappId=${id}\n`,
    'ios/edition.xcconfig': `// Generated by scripts/apply-edition.mjs (${editionOf(edition)}); do not edit.\nAPP_BUNDLE_ID = ${id}\n`,
  };
}
